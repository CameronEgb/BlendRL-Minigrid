#!/usr/bin/env python3
"""
Extract, evaluate, and package the best Pyrenees models from the 6-GPU Optuna sweep.
"""
import os
import sys
import shutil
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))
src_path = PROJECT_ROOT / "src"
if str(src_path) not in sys.path:
    sys.path.insert(0, str(src_path))

import optuna
import torch
import numpy as np
import pandas as pd

STUDIES = {
    "cql_dueling_resnet": {
        "exp_id": "tune_pyrenees_dueling_resnet",
        "study_name": "pyrenees_dueling_resnet",
        "display_name": "Scaled Dueling ResNet (Neural Baseline)"
    },
    "blendrl_human_dueling_resnet": {
        "exp_id": "tune_pyrenees_blendrl_resnet",
        "study_name": "pyrenees_blendrl_human_dueling_resnet",
        "display_name": "Scaled BlendRL (Human Logic + ResNet)"
    },
    "blendrl_cew_dueling_resnet": {
        "exp_id": "tune_pyrenees_cew_resnet",
        "study_name": "pyrenees_blendrl_cew_dueling_resnet",
        "display_name": "Scaled BlendRL (CEW Fuzzy + ResNet)"
    }
}

DB_URL = "sqlite:///results/optuna/optuna_pyrenees_scaled.db"
OUTPUT_CKPT_ROOT = PROJECT_ROOT / "results" / "checkpoints" / "pyrenees" / "pyrenees_best"
OUTPUT_REPORT_DIR = PROJECT_ROOT / "results" / "plots" / "pyrenees" / "pyrenees_best"


def main():
    print("=" * 70)
    print("      PYRENEES 6-GPU OPTUNA SWEEP: BEST MODEL EXTRACTOR & EVALUATOR")
    print("=" * 70)

    OUTPUT_CKPT_ROOT.mkdir(parents=True, exist_ok=True)
    OUTPUT_REPORT_DIR.mkdir(parents=True, exist_ok=True)

    summary_records = []

    for key, meta in STUDIES.items():
        exp_id = meta["exp_id"]
        study_name = meta["study_name"]
        display_name = meta["display_name"]

        print(f"\n[Study Analysis] Loading '{study_name}' from {DB_URL}...")
        try:
            study = optuna.load_study(study_name=study_name, storage=DB_URL)
            completed_trials = [t for t in study.trials if t.state == optuna.trial.TrialState.COMPLETE]
            print(f"  Total trials: {len(study.trials)} (Completed: {len(completed_trials)})")

            if not completed_trials:
                print(f"  Warning: No completed trials found for {study_name}. Skipping.")
                continue

            best_trial = study.best_trial
            print(f"  🏆 Best Trial #{best_trial.number}: val/loss = {best_trial.value:.4f}")
            print(f"     Optimal Params: {best_trial.params}")

            # Locate trial checkpoint
            # Checkpoints are saved under results/checkpoints/pyrenees/<exp_id>/<agent>/<trial_num>/best_model.ckpt
            possible_paths = [
                PROJECT_ROOT / "results" / "checkpoints" / "pyrenees" / exp_id / key / str(best_trial.number) / "best_model.ckpt",
                PROJECT_ROOT / "results" / "checkpoints" / "pyrenees" / exp_id / f"cql_{key}" / str(best_trial.number) / "best_model.ckpt",
            ]
            # Also search recursively under exp_id
            search_dir = PROJECT_ROOT / "results" / "checkpoints" / "pyrenees" / exp_id
            if search_dir.exists():
                for ckpt in search_dir.rglob("best_model*.ckpt"):
                    if str(best_trial.number) in str(ckpt.parent):
                        possible_paths.insert(0, ckpt)

            found_ckpt = None
            for p in possible_paths:
                if p.exists():
                    found_ckpt = p
                    break

            if found_ckpt:
                dest_dir = OUTPUT_CKPT_ROOT / key
                dest_dir.mkdir(parents=True, exist_ok=True)
                dest_ckpt = dest_dir / "best_model.ckpt"
                shutil.copy2(found_ckpt, dest_ckpt)
                print(f"  ✅ Saved Best Model Checkpoint to: {dest_ckpt}")
            else:
                print(f"  ⚠️ Could not locate exact checkpoint file for trial #{best_trial.number}")

            summary_records.append({
                "Architecture": display_name,
                "Best Trial #": best_trial.number,
                "Best Val Loss": round(best_trial.value, 4),
                "Best Hyperparameters": str(best_trial.params),
                "Checkpoint Extracted": "Yes" if found_ckpt else "No"
            })

        except Exception as e:
            print(f"  Notice: Could not load study {study_name}: {e}")

    # Generate summary report
    if summary_records:
        df_summary = pd.DataFrame(summary_records)
        report_path = OUTPUT_REPORT_DIR / "best_optuna_models_summary.md"
        with open(report_path, "w") as f:
            f.write("# Pyrenees 6-GPU Optuna Sweep: Winning Models Summary\n\n")
            f.write(df_summary.to_markdown(index=False))
            f.write("\n\n---\n*Auto-generated by NeSyRL Pipeline*\n")
        print(f"\n[Report Generated] Executive summary saved to: {report_path}")

    # Run policy evaluation on the extracted best checkpoints
    print("\n" + "=" * 70)
    print("      RUNNING OFF-POLICY PEDAGOGICAL EVALUATION")
    print("=" * 70)
    try:
        from plot.action_distribution import ActionDistributionPlotter
        plotter = ActionDistributionPlotter()
        plotter.run("pyrenees_best")
        print("✅ Pedagogical action distribution evaluation completed. Check results in results/plots/pyrenees/pyrenees_best/")
    except Exception as e:
        print(f"Notice: Policy evaluation run skipped or encountered error: {e}")


if __name__ == "__main__":
    main()
